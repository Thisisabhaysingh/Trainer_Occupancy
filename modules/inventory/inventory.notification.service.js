const { Notification, User } = require("../../models");
const { sendBrandedEmail } = require("../../services/emailService");

const escapeHtml = (value) => String(value ?? "")
  .replace(/&/g, "&amp;")
  .replace(/</g, "&lt;")
  .replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;")
  .replace(/'/g, "&#039;");

const betaSubject = (title) => `[BETA TEST] ${title}`;
const workflowUrl = (route) => {
  const baseUrl = String(process.env.FRONTEND_URL || "").replace(/\/$/, "");
  return baseUrl && route ? `${baseUrl}${route}` : null;
};

const queueInventoryEvents = async (transaction, events) => {
  const uniqueEvents = [...new Map(
    events
      .filter((event) => event.employeeCode)
      .map((event) => [`${event.employeeCode}:${event.type}:${event.title}`, event])
  ).values()];
  const emails = [];

  for (const event of uniqueEvents) {
    const recipient = await User.findByPk(event.employeeCode, {
      attributes: ["employeeCode", "name", "email"],
      transaction,
    });
    if (!recipient) continue;

    await Notification.create({
      userId: recipient.employeeCode,
      type: event.type || "notification",
      title: event.title,
      body: event.body,
      entityType: "inventory_request",
      entityId: event.requestId,
      metadata: {
        requestManifest: event.requestManifest,
        route: event.route || "/inventory/my-requests",
        stage: event.stage,
      },
    }, { transaction });

    if (recipient.email) emails.push({ recipient, event });
  }

  if (emails.length) {
    transaction.afterCommit(async () => {
      const results = await Promise.allSettled(emails.map(({ recipient, event }) => sendBrandedEmail({
        to: recipient.email,
        subject: betaSubject(event.title),
        title: event.title,
        intro: `Hello ${recipient.name || recipient.employeeCode}, ${event.body}`,
        bodyHtml: `
          <div style="margin:0 0 16px;padding:12px 14px;border:1px solid #F79009;border-radius:8px;background:#FFFAEB;color:#93370D;font-size:13px;font-weight:700;">
            Beta Version for Testing — this notification was generated by the MIS Beta workflow.
          </div>
          <table style="width:100%;border-collapse:collapse;font-size:14px;">
            <tr>
              <td style="padding:8px 12px;border:1px solid #EAECF0;color:#667085;">Request</td>
              <td style="padding:8px 12px;border:1px solid #EAECF0;font-weight:600;">${escapeHtml(event.requestManifest)}</td>
            </tr>
            <tr>
              <td style="padding:8px 12px;border:1px solid #EAECF0;color:#667085;">Status</td>
              <td style="padding:8px 12px;border:1px solid #EAECF0;font-weight:600;">${escapeHtml(event.stage)}</td>
            </tr>
          </table>
          ${workflowUrl(event.route) ? `
            <p style="margin:18px 0 0;">
              <a href="${escapeHtml(workflowUrl(event.route))}" style="display:inline-block;padding:10px 16px;border-radius:6px;background:#6941C6;color:#FFFFFF;text-decoration:none;font-weight:700;">
                ${event.route === "/inventory/approvals" ? "Review and approve or reject" : "Open inventory request"}
              </a>
            </p>
          ` : ""}
        `,
      })));
      results.forEach((result) => {
        if (result.status === "rejected") console.error("Inventory workflow email failed:", result.reason);
      });
    });
  }
};

module.exports = { queueInventoryEvents };
